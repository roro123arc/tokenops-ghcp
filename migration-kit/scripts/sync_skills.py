#!/usr/bin/env python3
"""
sync_skills.py - collect every repo's skills into the central repo, the Copilot way.

Replaces the Claude session-start sync. Run it from CI (see
.github/workflows/sync-skills.yml) or by hand. Skills land as real files
(no symlinks) in the central repo's .github/skills, each prefixed with its
repo name so two repos can never ship a skill with the same name.

  python3 sync_skills.py --repos repos.txt --workdir ../ --central .          # dry run
  python3 sync_skills.py --repos repos.txt --workdir ../ --central . --apply

repos.txt: one repo per line, "<prefix> <git url or local path>", # for comments.
"""
import argparse, re, shutil, subprocess, sys
from pathlib import Path

SKILL_DIRS = (".github/skills", ".claude/skills", ".agents/skills")


def read_repos(path: Path):
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            prefix, src = line.split(maxsplit=1)
            yield prefix, src


def git(*args, cwd=None):
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)


def ensure_repo(prefix, src, workdir: Path, apply: bool) -> Path:
    local = Path(src).expanduser()
    if local.is_dir():
        dest = local
    else:
        dest = workdir / prefix
        if not dest.exists():
            print(f"clone  {src} -> {dest}")
            if apply:
                r = git("clone", "--depth", "1", src, str(dest))
                if r.returncode:
                    print(f"  ! clone failed: {r.stderr.strip()}")
                    return None
            return dest if dest.exists() else None
    if (dest / ".git").exists():
        print(f"pull   {dest}")
        if apply:
            r = git("pull", "--ff-only", cwd=dest)
            if r.returncode:
                print(f"  ! pull failed: {r.stderr.strip()}")
    return dest


def set_name(skill_md: Path, new_name: str):
    text = skill_md.read_text(encoding="utf-8")
    text, n = re.subn(r"(?m)^(name:\s*).*$", rf"\g<1>{new_name}", text, count=1)
    if n == 0 and text.startswith("---"):
        text = text.replace("---\n", f"---\nname: {new_name}\n", 1)
    skill_md.write_text(text, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repos", type=Path, required=True)
    ap.add_argument("--workdir", type=Path, default=Path(".."), help="where remote repos are cloned")
    ap.add_argument("--central", type=Path, default=Path("."), help="the central repo")
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()

    target = a.central.resolve() / ".github" / "skills"
    seen, index = {}, []
    for prefix, src in read_repos(a.repos):
        repo = ensure_repo(prefix, src, a.workdir.resolve(), a.apply)
        if repo is None:
            continue
        for d in SKILL_DIRS:
            root = repo / d
            if not root.is_dir() or root.resolve() == target:
                continue
            for skill in sorted(p for p in root.iterdir() if (p / "SKILL.md").is_file()):
                base = skill.name if skill.name.startswith(prefix + "-") else f"{prefix}-{skill.name}"
                if base in seen:
                    print(f"  ! duplicate {base}: {seen[base]} and {skill} -> keeping the first")
                    continue
                seen[base] = skill
                dest = target / base
                print(f"copy   {skill} -> {dest}")
                index.append(f"| `{base}` | {prefix} | {d} |")
                if a.apply:
                    if dest.exists():
                        shutil.rmtree(dest)
                    shutil.copytree(skill, dest, symlinks=False)
                    set_name(dest / "SKILL.md", base)

    if a.apply:
        target.mkdir(parents=True, exist_ok=True)
        (target / "INDEX.md").write_text(
            "# Skills index (generated by sync_skills.py)\n\n| Skill | Repo | Source |\n| --- | --- | --- |\n"
            + "\n".join(index) + "\n", encoding="utf-8")
    print(f"\n{len(index)} skills {'synced' if a.apply else 'would be synced (dry run, use --apply)'}")


if __name__ == "__main__":
    sys.exit(main())
